-- BUG-375 BE-113: owners.name_kana / pets.name_kana のカタカナをひらがなに一括変換
--
-- 文字マッピング: U+30A1 (ァ) 〜 U+30F6 (ヶ) → U+3041 (ぁ) 〜 U+3096 (ゖ)
-- translate() は文字単位置換のため冪等（再実行しても結果不変）
-- ひらがな・漢字・英数字などマッピング外の文字はそのまま残る

