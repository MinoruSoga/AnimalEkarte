-- 1. owners テーブル (name_kana)
-- -----------------------------------------------------------------------------
UPDATE owners 
SET name_kana = translate(name_kana, 'ァアィイゥウェエォオカガキギクグケゲコゴサザシジスズセゼソゾタダチヂッツヅテデトドナニヌネノハバパヒビピフブプヘベペホボポマミムメモャヤュユョヨラリルレロワヲンー', 'ぁあぃいぅうぇえぉおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねのはばぱひびぴふぶぷへべぺほぼぽまみむめもゃやゅゆょよらりるれろわをんー')
WHERE name_kana IS NOT NULL AND name_kana != '';

-- -----------------------------------------------------------------------------
-- 2. pets テーブル (name_kana)
-- -----------------------------------------------------------------------------
UPDATE pets 
SET name_kana = translate(name_kana, 'ァアィイゥウェエォオカガキギクグケゲコゴサザシジスズセゼソゾタダチヂッツヅテデトドナニヌネノハバパヒビピフブプヘベペホボポマミムメモャヤュユョヨラリルレロワヲンー', 'ぁあぃいぅうぇえぉおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねのはばぱひびぴふぶぷへべぺほぼぽまみむめもゃやゅゆょよらりるれろわをんー')
WHERE name_kana IS NOT NULL AND name_kana != '';

-- -----------------------------------------------------------------------------
-- 3. 変換結果確認
-- -----------------------------------------------------------------------------
-- owners テーブル
SELECT 
    COUNT(*) as total_owners,
    COUNT(CASE WHEN name_kana ~ '[ァ-ヶ]' THEN 1 END) as owners_with_katakana
FROM owners WHERE name_kana IS NOT NULL AND name_kana != '';

-- pets テーブル
SELECT 
    COUNT(*) as total_pets,
    COUNT(CASE WHEN name_kana ~ '[ァ-ヶ]' THEN 1 END) as pets_with_katakana
FROM pets WHERE name_kana IS NOT NULL AND name_kana != '';

-- -----------------------------------------------------------------------------
-- 4. 変換完了レポート
-- -----------------------------------------------------------------------------
-- owners テーブルのカタカナフィールドをひらがなに変換（カタカナが含まれないことを制約）
ALTER TABLE owners ADD CONSTRAINT owners_name_kana_hiragana 
CHECK (name_kana !~ '[ァ-ヶ]' OR name_kana IS NULL OR name_kana = '');

-- pets テーブルのカタカナフィールドをひらがなに変換（カタカナが含まれないことを制約）
ALTER TABLE pets ADD CONSTRAINT pets_name_kana_hiragana 
CHECK (name_kana !~ '[ァ-ヶ]' OR name_kana IS NULL OR name_kana = '');

