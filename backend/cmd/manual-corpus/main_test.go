package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"testing"
)

func writeFixture(t *testing.T, fe, be string) {
	t.Helper()
	for _, cat := range []string{"screens", "workflows"} {
		dir := filepath.Join(fe, "src/features/manual/content", cat)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, "01-a.md"), []byte("---\ntitle: T\n---\nbody"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	os.MkdirAll(filepath.Join(fe, "src/constants"), 0o755)
	os.WriteFile(filepath.Join(fe, "src/constants/manual-search-dict.json"),
		[]byte(`{"stopwords":["方法"],"suffixes":["します"],"synonym_groups":[["会計","会計処理"]]}`), 0o644)
	os.MkdirAll(filepath.Join(be, "internal/manualarticle"), 0o755)
	os.MkdirAll(filepath.Join(be, "internal/support"), 0o755)
}

func TestGenerateWritesAndCheck(t *testing.T) {
	fe, be := t.TempDir(), t.TempDir()
	writeFixture(t, fe, be)
	if err := generate(fe, be, false); err != nil {
		t.Fatalf("generate: %v", err)
	}
	if err := generate(fe, be, true); err != nil {
		t.Fatalf("--check after write: %v", err)
	}
	// 改変後 --check は stale で非ゼロかつ無書き込み
	path := filepath.Join(be, "internal/manualarticle/corpus.generated.json")
	stale := []byte(`{"articles":[],"revision":""}`)
	os.WriteFile(path, stale, 0o644)
	if err := generate(fe, be, true); err == nil {
		t.Fatal("--check must fail on stale artifact")
	}
	raw, _ := os.ReadFile(path)
	if string(raw) != string(stale) {
		t.Fatal("--check must not write")
	}
}

func TestGenerateRevisionConstantMatchesFrontendFormatting(t *testing.T) {
	fe, be := t.TempDir(), t.TempDir()
	writeFixture(t, fe, be)
	if err := generate(fe, be, false); err != nil {
		t.Fatal(err)
	}
	raw, err := os.ReadFile(filepath.Join(be, "internal/manualarticle/corpus.generated.json"))
	if err != nil {
		t.Fatal(err)
	}
	var metadata struct {
		Revision string `json:"revision"`
	}
	if err := json.Unmarshal(raw, &metadata); err != nil {
		t.Fatal(err)
	}
	if len(metadata.Revision) != 64 {
		t.Fatalf("expected SHA-256 revision, got %q", metadata.Revision)
	}
	got, err := os.ReadFile(filepath.Join(fe, "src/constants/manual-corpus.generated.ts"))
	if err != nil {
		t.Fatal(err)
	}
	want := fmt.Sprintf("// Code generated by cmd/manual-corpus. DO NOT EDIT.\nexport const MANUAL_CORPUS_BASE_REVISION =\n  %q;\n", metadata.Revision)
	if string(got) != want {
		t.Fatalf("generated revision constant differs from frontend formatting:\ngot %q\nwant %q", got, want)
	}
}

func TestGenerateErrors(t *testing.T) {
	fe, be := t.TempDir(), t.TempDir()
	writeFixture(t, fe, be)
	os.Remove(filepath.Join(fe, "src/features/manual/content/screens/01-a.md"))
	if err := generate(fe, be, false); err == nil {
		t.Fatal("empty screens dir must error")
	}
	writeFixture(t, fe, be)
	os.WriteFile(filepath.Join(fe, "src/features/manual/content/screens/日本語.md"), []byte("x"), 0o644)
	if err := generate(fe, be, false); err == nil {
		t.Fatal("non-ASCII slug must error")
	}
}
