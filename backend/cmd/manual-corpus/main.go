// cmd/manual-corpus は frontend/src/features/manual/content/{screens,workflows}/*.md
// から決定的 base コーパス JSON を生成し、3 成果物を書き出す:
//  1. backend/internal/manualarticle/corpus.generated.json
//  2. frontend/src/constants/manual-corpus.generated.ts
//  3. backend/internal/support/search_dict.go（manual-search-dict.json 由来）
//
// 人間実行 codegen 経路のみ。--check は比較のみ（書き込まない）。
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/animal-ekarte/backend/internal/manualarticle"
)

var slugRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9_-]{0,99}$`)

type searchDict struct {
	Stopwords     []string   `json:"stopwords"`
	Suffixes      []string   `json:"suffixes"`
	SynonymGroups [][]string `json:"synonym_groups"`
}

// readManualSource confines reads, including symlinks, to the operator-selected root.
func readManualSource(frontendDir, name string) ([]byte, error) {
	root, err := os.OpenRoot(frontendDir)
	if err != nil {
		return nil, err
	}
	raw, readErr := fs.ReadFile(root.FS(), filepath.ToSlash(name))
	return raw, errors.Join(readErr, root.Close())
}

func loadMarkdownCorpus(frontendDir string) ([]manualarticle.CorpusArticle, error) {
	var out []manualarticle.CorpusArticle
	seen := map[string]struct{}{}
	for _, category := range []string{"screens", "workflows"} {
		dir := filepath.Join(frontendDir, "src", "features", "manual", "content", category)
		entries, err := filepath.Glob(filepath.Join(dir, "*.md"))
		if err != nil {
			return nil, err
		}
		if len(entries) == 0 {
			return nil, fmt.Errorf("no markdown files in %s", category)
		}
		sort.Strings(entries)
		for _, path := range entries {
			relative, err := filepath.Rel(frontendDir, path)
			if err != nil {
				return nil, err
			}
			raw, err := readManualSource(frontendDir, relative)
			if err != nil {
				return nil, err
			}
			slug := strings.TrimSuffix(filepath.Base(path), ".md")
			if !slugRe.MatchString(slug) {
				return nil, fmt.Errorf("invalid slug %q", slug)
			}
			key := category + "/" + slug
			if _, dup := seen[key]; dup {
				return nil, fmt.Errorf("duplicate article %s", key)
			}
			seen[key] = struct{}{}
			out = append(out, manualarticle.BaseCorpusArticleFromMarkdown(category, slug, string(raw)))
		}
	}
	return out, nil
}

func goDictSource(d searchDict) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/manual-corpus from frontend/src/constants/manual-search-dict.json. DO NOT EDIT.\n")
	b.WriteString("package support\n\n")
	b.WriteString("var searchDictStopwords = map[string]struct{}{\n")
	for _, w := range d.Stopwords {
		fmt.Fprintf(&b, "\t%q: {},\n", w)
	}
	b.WriteString("}\n\nvar searchDictSuffixes = []string{\n")
	for _, w := range d.Suffixes {
		fmt.Fprintf(&b, "\t%q,\n", w)
	}
	b.WriteString("}\n\nvar searchDictSynonymGroups = [][]string{\n")
	for _, g := range d.SynonymGroups {
		b.WriteString("\t{")
		for i, w := range g {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", w)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\nvar searchDictSegmentSet = func() map[string]struct{} {\n\tm := make(map[string]struct{})\n\tfor _, g := range searchDictSynonymGroups {\n\t\tfor _, w := range g {\n\t\t\tm[w] = struct{}{}\n\t\t}\n\t}\n\treturn m\n}()\n")
	return format.Source([]byte(b.String()))
}

// validateSearchDict は dict の構造的正当性を確認する（値の調整はしない）。
func validateSearchDict(d searchDict) error {
	if len(d.Stopwords) == 0 || len(d.Suffixes) == 0 || len(d.SynonymGroups) == 0 {
		return errors.New("manual-search-dict.json has empty required list")
	}
	seenStop := map[string]struct{}{}
	for _, w := range d.Stopwords {
		if w == "" {
			return errors.New("manual-search-dict.json has empty stopword")
		}
		if _, dup := seenStop[w]; dup {
			return fmt.Errorf("duplicate stopword %q", w)
		}
		seenStop[w] = struct{}{}
	}
	seenSuf := map[string]struct{}{}
	for _, w := range d.Suffixes {
		if w == "" {
			return errors.New("manual-search-dict.json has empty suffix")
		}
		if _, dup := seenSuf[w]; dup {
			return fmt.Errorf("duplicate suffix %q", w)
		}
		seenSuf[w] = struct{}{}
	}
	memberOf := map[string]int{}
	for _, g := range d.SynonymGroups {
		if len(g) < 2 {
			return errors.New("synonym group must have >=2 terms")
		}
		inGroup := map[string]struct{}{}
		for _, w := range g {
			if w == "" {
				return errors.New("empty term in synonym group")
			}
			if _, dup := inGroup[w]; dup {
				return fmt.Errorf("duplicate term %q within synonym group", w)
			}
			inGroup[w] = struct{}{}
			memberOf[w]++
		}
	}
	for w, n := range memberOf {
		if n > 1 {
			return fmt.Errorf("term %q belongs to multiple synonym groups", w)
		}
	}
	return nil
}

func generate(frontendDir, backendDir string, check bool) error {
	base, err := loadMarkdownCorpus(frontendDir)
	if err != nil {
		return err
	}
	dictRaw, err := readManualSource(frontendDir, filepath.Join("src", "constants", "manual-search-dict.json"))
	if err != nil {
		return err
	}
	var dict searchDict
	if err := json.Unmarshal(dictRaw, &dict); err != nil {
		return errors.New("malformed manual-search-dict.json")
	}
	if err := validateSearchDict(dict); err != nil {
		return err
	}
	corpus := manualarticle.BuildCorpus(base, nil)
	corpusJSON := append([]byte(`{"articles":`), manualarticle.CanonicalCorpusJSON(corpus.Articles)...)
	corpusJSON = append(corpusJSON, []byte(`,"revision":"`+corpus.Revision+`"}`)...)
	corpusJSON = append(corpusJSON, '\n')
	tsConst := []byte("// Code generated by cmd/manual-corpus. DO NOT EDIT.\nexport const MANUAL_CORPUS_BASE_REVISION =\n  \"" + corpus.Revision + "\";\n")
	goDict, err := goDictSource(dict)
	if err != nil {
		return err
	}
	targets := []struct {
		path string
		data []byte
	}{
		{filepath.Join(backendDir, "internal", "manualarticle", "corpus.generated.json"), corpusJSON},
		{filepath.Join(frontendDir, "src", "constants", "manual-corpus.generated.ts"), tsConst},
		{filepath.Join(backendDir, "internal", "support", "search_dict.go"), goDict},
	}
	for _, t := range targets {
		existing, rerr := os.ReadFile(t.path)
		if check {
			if rerr != nil {
				return fmt.Errorf("missing generated artifact %s", filepath.Base(t.path))
			}
			if !bytes.Equal(existing, t.data) {
				return fmt.Errorf("stale generated artifact %s", filepath.Base(t.path))
			}
			continue
		}
		// #nosec G306 -- These public, checked-in corpus/dictionary assets must be readable by build consumers.
		if err := os.WriteFile(t.path, t.data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func main() {
	frontendDir := flag.String("frontend", "../frontend", "frontend repo root")
	backendDir := flag.String("backend", ".", "backend repo root")
	check := flag.Bool("check", false, "compare without writing")
	flag.Parse()
	if err := generate(*frontendDir, *backendDir, *check); err != nil {
		fmt.Fprintf(os.Stderr, `{"error":%q}`+"\n", err.Error())
		os.Exit(1)
	}
}
